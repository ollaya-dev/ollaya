// Reads the static model registry (../registry, written by convert/ollaya_convert/package.py) and
// writes src/generated/registry.ts — the facts behind every model and tag page on the site.
//
//   registry/v2/<namespace>/<model>/manifests/<tag>   OCI-style manifests
//   registry/blobs/sha256-<hex>                      derived blobs (config, router, decision, …)
//
// Weights and tokenizers live on the model authors' Hugging Face repos, referenced by URL in the
// manifests; they are never read here. Small JSON blobs (config, router, params, decision,
// calibration) are read when present locally. A missing registry produces an empty catalog.
//
// Env: OLLAYA_REGISTRY_DIR overrides the registry location.

import { createHash } from 'node:crypto'
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const registry = resolve(process.env.OLLAYA_REGISTRY_DIR || join(root, '..', 'registry'))
const outFile = join(root, 'src', 'generated', 'registry.ts')

const MEDIA = 'application/vnd.ollaya.'

async function readJsonBlob(digest) {
  try {
    return JSON.parse(await readFile(join(registry, 'blobs', digest.replace(':', '-')), 'utf8'))
  } catch {
    return undefined
  }
}

async function readTextBlob(digest) {
  try {
    return await readFile(join(registry, 'blobs', digest.replace(':', '-')), 'utf8')
  } catch {
    return undefined
  }
}

async function dirs(p) {
  try {
    return (await readdir(p, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name).sort()
  } catch {
    return []
  }
}

async function files(p) {
  try {
    return (await readdir(p, { withFileTypes: true })).filter((e) => e.isFile()).map((e) => e.name).sort()
  } catch {
    return []
  }
}

async function readTag(ns, model, tag) {
  const path = join(registry, 'v2', ns, model, 'manifests', tag)
  const bytes = await readFile(path)
  const manifest = JSON.parse(bytes.toString('utf8'))
  const config = (await readJsonBlob(manifest.config.digest)) ?? {}
  const layers = []
  let router, params, decision, calibration, license
  for (const l of manifest.layers ?? []) {
    const kind = l.mediaType.startsWith(MEDIA) ? l.mediaType.slice(MEDIA.length).split('.')[0] : l.mediaType
    const layer = {
      kind,
      mediaType: l.mediaType,
      digest: l.digest,
      size: l.size,
      url: (l.urls ?? [])[0] ?? null,
      precision: l.annotations?.['org.ollaya.precision'] ?? null,
    }
    layers.push(layer)
    if (kind === 'router') router = await readJsonBlob(l.digest)
    else if (kind === 'params') params = await readJsonBlob(l.digest)
    else if (kind === 'decision') decision = await readJsonBlob(l.digest)
    else if (kind === 'calibration') calibration = await readJsonBlob(l.digest)
    else if (kind === 'license') license = (await readTextBlob(l.digest))?.split('\n').find((s) => s.trim())?.trim()
  }
  return {
    name: tag,
    digest: createHash('sha256').update(bytes).digest('hex'),
    configDigest: manifest.config.digest,
    size: manifest.config.size + layers.reduce((n, l) => n + l.size, 0),
    config: {
      format: config.model_format ?? '',
      family: config.family ?? model,
      parameterSize: config.parameter_size ?? '',
      contextLength: config.context_length ?? 0,
      languages: config.languages ?? [],
      description: config.description ?? '',
      source: config.source ?? '',
      license: config.license ?? '',
      releaseDate: config.release_date ?? null,
    },
    layers,
    router: router ?? null,
    precision: params?.precision ?? null,
    encoder: decision?.encoder ?? null,
    layout: decision?.layout ?? null,
    calibrationKeys: calibration ? Object.keys(calibration.temperature_by_options ?? {}) : null,
    licenseLine: license ?? null,
  }
}

const models = []
for (const ns of await dirs(join(registry, 'v2'))) {
  for (const model of await dirs(join(registry, 'v2', ns))) {
    const tags = []
    for (const tag of await files(join(registry, 'v2', ns, model, 'manifests'))) {
      try {
        tags.push(await readTag(ns, model, tag))
      } catch (e) {
        throw new Error(`registry/v2/${ns}/${model}/manifests/${tag}: ${e.message}`)
      }
    }
    if (tags.length) models.push({ namespace: ns, name: model, tags })
  }
}

const header = '// AUTO-GENERATED by scripts/gen-registry.mjs from ../registry — do not edit. Run `npm run gen`.\n\n'
const types = `export interface RegistryLayer {
  /** Last part of the media type: graph, weights, tokenizer, decision, calibration, license, router, params. */
  kind: string
  mediaType: string
  digest: string
  size: number
  /** Where the client downloads it from (Hugging Face for weights and tokenizers). */
  url: string | null
  precision: string | null
}

export interface RegistryTag {
  name: string
  /** sha256 of the manifest bytes, bare hex (what \`ollaya list\` shows, shortened). */
  digest: string
  configDigest: string
  /** Bytes of the config and every layer. */
  size: number
  config: {
    format: string
    family: string
    parameterSize: string
    contextLength: number
    languages: string[]
    description: string
    source: string
    license: string
    releaseDate: string | null
  }
  layers: RegistryLayer[]
  router: { strategy: string; default: string; routes: Record<string, string> } | null
  /** Pinned precision (from the params layer), or null when the tag carries both graphs. */
  precision: string | null
  encoder: string | null
  layout: string | null
  calibrationKeys: string[] | null
  licenseLine: string | null
}

export interface RegistryModel {
  namespace: string
  name: string
  tags: RegistryTag[]
}
`
await mkdir(join(root, 'src', 'generated'), { recursive: true })
await writeFile(outFile, `${header}${types}\nexport const registryModels: RegistryModel[] = ${JSON.stringify(models, null, 2)}\n`)
console.log(
  `registry: ${models.length} model(s), ${models.reduce((n, m) => n + m.tags.length, 0)} tag(s) from ${registry}`,
)
